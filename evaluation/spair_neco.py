CLASSES = ['aeroplane', 'bicycle', 'bird', 'boat', 'bottle', 'bus', 'car',
           'cat', 'chair', 'cow', 'dog', 'horse', 'motorbike', 'person',
           'pottedplant', 'sheep', 'train', 'tvmonitor']
THRESHOLDS = (0.01, 0.1)


def digest(path):
    h = hashlib.sha256()
    with Path(path).open('rb') as handle:
        for chunk in iter(lambda: handle.read(8 * 1024 * 1024), b''):
            h.update(chunk)
    return h.hexdigest()


def save(path, value):
    path = Path(path)
    temp = path.with_suffix(path.suffix + '.tmp')
    temp.write_text(json.dumps(value, indent=2) + '\n')
    temp.replace(path)


def prepare(args):
    root = args.root.resolve()
    root.mkdir(parents=True, exist_ok=False)
    previous = args.annotations_run.resolve()
    native = args.native_run.resolve()
    source = root / 'source'
    shutil.copytree(native / 'source', source, symlinks=True,
                    ignore=shutil.ignore_patterns('__pycache__', '*.pyc'))
    # Use the official evaluator and loader, rather than a rewritten matcher.
    upstream = args.upstream_sources.resolve()
    for rel in ('evaluate_spair_correspondence.py', 'evals/datasets/spair.py',
                'configs/spair_correspondence.yaml'):
        shutil.copy2(upstream / rel, source / rel)
    shutil.copy2(Path(__file__), root / 'runner.py')
    shutil.copy2(PROJECT / 'slurm/evaluation_spair_neco.sh', root / 'launch.sh')
    shutil.copy2(previous / 'annotations.json', root / 'annotations.json')
    data = json.loads((root / 'annotations.json').read_text())
    by_name = {a['filename']: a for a in data['pairs']}
    old_manifest = json.loads((previous / 'manifest.json').read_text())
    data_root = Path(old_manifest['data_root'])
    layout = (data_root / 'Layout/large/test.txt').read_text().splitlines()
    assert len(layout) == 12234 and len(set(layout)) == 12234
    assert layout == [a['filename'] for a in data['pairs']]
    assert digest(root / 'annotations.json') == old_manifest['annotations_sha256']
    # Existing pinned native pairs were generated by the upstream seed-20
    # sampler. Pin them instead of depending on filesystem glob enumeration.
    native_pairs = json.loads((native / 'preflight_manifest.json').read_text())['spair']
    sampled = []
    for category in CLASSES:
        names = native_pairs[category + '/None']
        assert len(names) == min(200, sum(a['category'] == category for a in data['pairs']))
        assert len(set(names)) == len(names)
        assert all(by_name[n]['category'] == category for n in names)
        sampled.extend(names)
    assert len(set(sampled)) == len(sampled)
    selected = set(sampled)
    execution_order = sampled + [n for n in layout if n not in selected]
    assert len(execution_order) == len(layout) and set(execution_order) == set(layout)
    save(root / 'pairs.json', {'sampled': sampled, 'full': layout, 'execution_order': execution_order})
    checkpoints = {}
    for name, path in MODELS.items():
        print('Checking checkpoint hash', name, flush=True)
        expected = old_manifest['checkpoints'][name]
        assert digest(path) == expected['sha256'], name
        checkpoints[name] = expected
        (root / name).mkdir()
    hashes = {str(p.relative_to(source)): digest(p) for p in source.rglob('*')
              if p.is_file() and p.suffix in ('.py', '.yaml')}
    save(root / 'manifest.json', {
        'data_root': str(data_root), 'checkpoints': checkpoints,
        'source_sha256': hashes, 'runner_sha256': digest(root / 'runner.py'),
        'annotations_sha256': digest(root / 'annotations.json'),
        'pairs_sha256': digest(root / 'pairs.json'),
        'categories': CLASSES, 'test_pairs': len(layout), 'sampled_pairs': len(sampled),
        'sampled_pair_counts': dict(Counter(by_name[n]['category'] for n in sampled)),
        'sources': {
            'neco_paper': 'https://arxiv.org/html/2408.11054v3#S4.T5',
            'neco_repo': 'https://github.com/vpariza/NeCo',
            'probe3d_commit': 'a1f14640076e38b8bc07b66d0fe2d01d15691e9d',
            'spair_official': 'https://cvlab.postech.ac.kr/research/SPair-71k/',
            'hpf_evaluator': 'https://github.com/juhongm999/hpf/blob/239be4208f970dca9ab5679517b781eb627487d0/model/evaluation.py',
        },
        'protocol': {
            'image_size': 224, 'patch_grid': [14, 14], 'image_mean': 'imagenet',
            'features': 'teacher raw final block 12 before LayerNorm, no head or softmax',
            'matching': 'unmodified official Probe3D compute_errors, mask_feats=False',
            'preprocessing': 'Probe3D white square padding then bicubic resize; integer keypoints',
            'bbox_crop': False, 'test_time_augmentation': False,
            'threshold_scale': 'longest target bounding-box side (Probe3D)',
            'primary_threshold': 0.01, 'diagnostic_threshold': 0.1,
            'primary_aggregation': 'pooled keypoint recall within category; unweighted mean of 18 categories',
            'primary_pairs': 'released Probe3D default: up to 200 per category, seed 20; pinned list',
            'full_test_secondary': 'all 12234 official test pairs, same matching',
            'official_spair_secondary': 'per-pair PCK average, <= threshold (HPF)',
            'limitations': [
                'NeCo does not release its SPair evaluator or exact sampled pairs; defaults are inferred from cited Probe3D code.',
                'NeCo Table 5 caption says Recall@0.01 while released Probe3D defaults to 0.1; both are reported separately.',
            ],
        },
    })
    collect(args)
    print('Prepared', root, 'sampled pairs', len(sampled), 'full pairs', len(layout), flush=True)


def summarize(rows):
    assert rows
    def metrics(selected, threshold):
        key = str(threshold)
        total = sum(r['keypoints'] for r in selected)
        return {
            'recall': 100 * sum(r['correct_strict'][key] for r in selected) / total,
            'official_pair_pck': 100 * sum(r['correct_inclusive'][key] / r['keypoints'] for r in selected) / len(selected),
            'pairs': len(selected), 'keypoints': total,
        }
    result = {}
    for threshold in THRESHOLDS:
        classes = {c: metrics([r for r in rows if r['category'] == c], threshold)
                   for c in CLASSES if any(r['category'] == c for r in rows)}
        result[str(threshold)] = {
            'per_category': classes,
            'category_macro_recall': sum(m['recall'] for m in classes.values()) / len(classes),
            'pooled': metrics(rows, threshold),
        }
    return result


def read_journal(path):
    # Recover only an incomplete final write if a job was interrupted.
    if not path.exists():
        return []
    raw = path.read_bytes()
    if raw and not raw.endswith(b'\n'):
        raw = raw[:raw.rfind(b'\n') + 1]
        path.write_bytes(raw)
    return [json.loads(line) for line in raw.splitlines()]


def run(args):
    import torch
    root = args.root.resolve()
    manifest = json.loads((root / 'manifest.json').read_text())
    source = root / 'source'
    for rel, expected in manifest['source_sha256'].items():
        assert digest(source / rel) == expected, rel
    for name in ('runner', 'annotations', 'pairs'):
        path = root / (name + ('.py' if name == 'runner' else '.json'))
        assert digest(path) == manifest[name + '_sha256'], name
    identity = manifest['checkpoints'][args.model]
    assert digest(identity['path']) == identity['sha256']
    sys.path.insert(0, str(source))
    os.chdir(source)
    from evals.datasets.spair import SPairDataset
    from evals.models.region_vits import RegionViTS
    from evaluate_spair_correspondence import compute_errors
    data = json.loads((root / 'annotations.json').read_text())
    pairs = json.loads((root / 'pairs.json').read_text())
    annotations = {a['filename']: a for a in data['pairs']}

    class OrderedSPair(SPairDataset):
        def get_pair_annotations(self):
            return [annotations[n] for n in pairs['execution_order']]

        def get_image_annotations(self):
            return data['images']

    torch.set_num_threads(4)
    torch.set_grad_enabled(False)
    assert torch.cuda.is_available()
    model = RegionViTS(identity['path'], output='dense', return_multilayer=False).cuda().eval()
    assert model.multilayers == [11] and model.feat_dim == 384 and model.patch_size == 16
    assert not any(p.requires_grad for p in model.parameters())
    checkpoint = torch.load(identity['path'], map_location='cpu')
    epoch = checkpoint['epoch']
    assert epoch == (200 if args.model == 'region200' else 800), epoch
    del checkpoint
    dataset = OrderedSPair(manifest['data_root'], 'test', image_size=224,
                           image_mean='imagenet', use_bbox=False, num_instances=None)
    assert len(dataset) == 12234
    out = root / args.model
    journal = out / 'pairs.jsonl'
    rows = read_journal(journal)
    for i, row in enumerate(rows):
        assert row['filename'] == pairs['execution_order'][i]
    sampled_count = manifest['sampled_pairs']
    started = time.monotonic()
    with torch.inference_mode():
        instance = dataset[0]
        assert instance[0].shape == instance[3].shape == (3, 224, 224)
        batch = torch.stack([instance[0], instance[3]]).cuda()
        features = model(batch)
        assert features.shape == (2, 384, 14, 14) and torch.isfinite(features).all()
        tokens = model.vit.prepare_tokens(batch)
        for block in model.vit.blocks:
            tokens = block(tokens)
        explicit = tokens[:, 1:].transpose(1, 2).reshape(2, 384, 14, 14)
        torch.testing.assert_close(features, explicit, rtol=0, atol=0)
        errors = compute_errors(model, instance)[0]
        assert errors.numel() == len(annotations[pairs['execution_order'][0]]['kps_ids'])
        assert torch.isfinite(errors).all()
        save(out / 'preflight.json', {'passed': True, 'epoch': epoch, 'checkpoint': identity,
             'feature_shape': list(features.shape), 'raw_block_equivalence': 'bit exact',
             'gpu': torch.cuda.get_device_name(),
             'peak_gpu_memory_gib': torch.cuda.max_memory_allocated() / 1024**3})
        del features, explicit, tokens, batch
        print('PREFLIGHT PASS', args.model, 'start pair', len(rows), flush=True)
        if len(rows) >= sampled_count:
            save(out / 'results_sampled.json', {'status': 'completed', 'model': args.model,
                 'checkpoint': identity, 'protocol': manifest['protocol'],
                 'metrics': summarize(rows[:sampled_count])})
        with journal.open('a', buffering=1) as handle:
            for i in range(len(rows), len(dataset)):
                a = annotations[pairs['execution_order'][i]]
                errors = compute_errors(model, dataset[i])[0]
                assert errors.numel() == len(a['kps_ids']) and errors.numel() > 0
                assert torch.isfinite(errors).all()
                row = {'filename': a['filename'], 'category': a['category'],
                       'keypoints': errors.numel(), 'normalized_errors': errors.tolist(),
                       'correct_strict': {str(t): int((errors < t).sum()) for t in THRESHOLDS},
                       'correct_inclusive': {str(t): int((errors <= t).sum()) for t in THRESHOLDS}}
                handle.write(json.dumps(row) + '\n')
                rows.append(row)
                if i + 1 == sampled_count:
                    save(out / 'results_sampled.json', {'status': 'completed', 'model': args.model,
                         'checkpoint': identity, 'protocol': manifest['protocol'],
                         'metrics': summarize(rows)})
                    print('SAMPLED TABLE COMPLETE', args.model, flush=True)
                if (i + 1) % 100 == 0:
                    print(args.model, 'pairs', i + 1, '/', len(dataset), 'minutes',
                          round((time.monotonic() - started) / 60, 1), flush=True)
    save(out / 'results_full.json', {'status': 'completed', 'model': args.model,
         'checkpoint': identity, 'protocol': manifest['protocol'], 'epoch': epoch,
         'elapsed_seconds': time.monotonic() - started, 'metrics': summarize(rows)})
    print('COMPLETED', args.model, flush=True)


def collect(args):
    root = args.root.resolve()
    results, lines, tex = {}, ['# NeCo Table 5 protocol: SPair-71k, 224 pixels', ''], []
    for selection in ('sampled', 'full'):
        results[selection] = {}
        for threshold in THRESHOLDS:
            lines.extend([f'## {selection}, Recall@{threshold}', '',
                          '| Model | ' + ' | '.join(CLASSES + ['Avg']) + ' |',
                          '|---|' + '---:|' * (len(CLASSES) + 1)])
            for model in MODELS:
                path = root / model / ('results_' + selection + '.json')
                entry = json.loads(path.read_text()) if path.exists() else {'status': 'not_finished'}
                results[selection][model] = entry
                if entry['status'] == 'completed':
                    m = entry['metrics'][str(threshold)]
                    scores = [f"{m['per_category'][c]['recall']:.2f}" for c in CLASSES]
                    scores.append(f"{m['category_macro_recall']:.2f}")
                else:
                    scores = ['--'] * (len(CLASSES) + 1)
                lines.append('| ' + model + ' | ' + ' | '.join(scores) + ' |')
                if selection == 'sampled' and threshold == 0.01:
                    label = r'iBOT~\cite{zhou2022ibot}' if model == 'ibot_original' else r'\rowcolor{blue}\textbf{Ours}'
                    tex.append(label + ' & ' + ' & '.join(scores) + r' \\')
            lines.append('')
    lines.extend(['NeCo publishes no exact SPair pairs or evaluator. The sampled table uses',
                  'Probe3D defaults. Recall@0.01 follows the paper caption; Recall@0.1 is diagnostic.',
                  'Official per-pair SPair/HPF PCK is also saved in each results JSON.'])
    save(root / 'results.json', results)
    (root / 'results_summary.md').write_text('\n'.join(lines) + '\n')
    (root / 'table_rows.tex').write_text('\n'.join(tex) + '\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=['prepare', 'run', 'collect'])
    parser.add_argument('--root', type=Path, required=True)
    parser.add_argument('--model', choices=list(MODELS))
    parser.add_argument('--annotations-run', type=Path, default=PROJECT / 'output/analysis/spair_nuisance_20261007_official')
    parser.add_argument('--native-run', type=Path, default=PROJECT / 'output/analysis/crisp_native_region200_20261007_163653')
    parser.add_argument('--upstream-sources', type=Path, default=PROJECT / 'evaluation/vendor/probe3d')
    args = parser.parse_args()
    if args.action == 'run' and args.model is None:
        parser.error('--model is required for run')
    globals()[args.action](args)


if __name__ == '__main__':
    main()
