"""NeCo Table 5: Probe3D SPair matching at 224 pixels and Recall@0.01.

NeCo publishes neither its SPair evaluator nor its pair list. The primary
report uses Probe3D's released 200-pairs-per-category default; a second report
uses all 12,234 official test pairs. Both retain upstream matching verbatim.
"""
import argparse
